create extension if not exists postgis;
create extension if not exists pg_trgm;

create function set_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end
$$;

create table users (
  id            integer generated by default as identity primary key,
  name          text not null,
  email         text not null,
  role          text not null check (role in ('Administrator','Management','Trade Coordinator')),
  province      text,
  scope         text not null default 'own_area' check (scope in ('national','own_area')),
  pw_hash       text,
  pw_salt       text,
  pw_iter       integer,
  must_change   boolean not null default true,
  fails         integer not null default 0,
  lock_until    timestamptz,
  overrides     jsonb not null default '{}',
  status        text not null default 'Active' check (status in ('Active','Suspended')),
  last_login_at timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create unique index users_email_key on users (lower(email));
create index users_role_idx on users (role);
create trigger users_set_updated_at before update on users
  for each row execute function set_updated_at();

create table provinces (
  key               text primary key,
  name_th           text not null,
  name_en           text,
  center            geometry(Point,4326),
  boundary          geometry(MultiPolygon,4326),
  has_district_data boolean not null default false
);
create index provinces_boundary_gix on provinces using gist (boundary);

create table mapping_templates (
  id               bigint generated always as identity primary key,
  name             text not null unique,
  header_signature text not null,
  mapping          jsonb not null,
  created_by       integer references users(id) on delete set null,
  created_at       timestamptz not null default now()
);
create index mapping_templates_signature_idx on mapping_templates (header_signature);

create table import_files (
  file_id      bigint generated always as identity primary key,
  filename     text not null,
  size_bytes   bigint not null check (size_bytes > 0 and size_bytes <= 26214400),
  rows_total   integer not null default 0,
  rows_ok      integer not null default 0,
  rows_error   integer not null default 0,
  rows_dup     integer not null default 0,
  rows_skipped integer not null default 0,
  mapping      jsonb not null default '{}',
  template_id  bigint references mapping_templates(id) on delete set null,
  uploaded_by  integer references users(id) on delete set null,
  uploaded_at  timestamptz not null default now(),
  status       text not null default 'pending'
               check (status in ('pending','processing','completed','partial','failed','withdrawn')),
  withdrawn_by integer references users(id) on delete set null,
  withdrawn_at timestamptz
);
create index import_files_uploaded_at_idx on import_files (uploaded_at desc);

create table places (
  id             text primary key check (char_length(id) between 1 and 20),
  type           text not null check (type in ('Existing','Prospect')),
  account_no     text,
  business_name  text not null,
  category       text,
  segment        text not null,
  country        text not null default 'Thailand',
  province       text not null references provinces(key),
  district       text,
  address        text,
  latitude       numeric(9,6) not null check (latitude between 5.5 and 20.6),
  longitude      numeric(9,6) not null check (longitude between 97 and 106),
  geom           geometry(Point,4326) generated always as
                 (ST_SetSRID(ST_MakePoint(longitude::double precision, latitude::double precision), 4326)) stored,
  phone          text,
  email          text,
  website        text,
  facebook       text,
  date_join      date,
  tc_owner_id    integer references users(id) on delete set null,
  visit_status   text,
  source         text not null default 'import_file'
                 check (source in ('seed','import_file','manual_admin','manual_tc')),
  import_file_id bigint references import_files(file_id) on delete set null,
  needs_review   boolean not null default false,
  converted_at   timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  deleted_at     timestamptz
);
create index places_scope_idx on places (type, province, district) where deleted_at is null;
create index places_tc_owner_idx on places (tc_owner_id) where deleted_at is null;
create index places_segment_idx on places (segment) where deleted_at is null;
create index places_account_no_idx on places (account_no) where account_no is not null;
create index places_created_at_idx on places (created_at);
create index places_import_file_idx on places (import_file_id) where import_file_id is not null;
create index places_geom_gix on places using gist (geom);
create index places_name_trgm on places using gin (business_name gin_trgm_ops);
create trigger places_set_updated_at before update on places
  for each row execute function set_updated_at();

create view customers as
  select * from places where type = 'Existing' and deleted_at is null;
create view leads as
  select * from places where type = 'Prospect' and deleted_at is null;

create table place_visits (
  id            bigint generated always as identity primary key,
  place_id      text not null references places(id) on delete cascade,
  round         integer not null check (round >= 1),
  status        text not null check (status in ('นัดแล้ว','เสร็จสิ้น','ยกเลิก')),
  appt_date     date,
  done_date     date,
  tc_id         integer references users(id) on delete set null,
  interest      text,
  outcome       text,
  note          text,
  cancel_reason text,
  created_at    timestamptz not null default now(),
  unique (place_id, round)
);
create index place_visits_tc_idx on place_visits (tc_id, done_date);
create index place_visits_status_idx on place_visits (status, appt_date);

create table import_rows (
  id             bigint generated always as identity primary key,
  file_id        bigint not null references import_files(file_id) on delete cascade,
  row_no         integer not null,
  kind           text not null check (kind in ('incomplete','dup','badcoord')),
  raw            jsonb not null,
  corrected      jsonb,
  issues         jsonb not null default '[]',
  match_place_id text references places(id) on delete set null,
  similarity     numeric(4,3) check (similarity between 0 and 1),
  status         text not null default 'pending'
                 check (status in ('pending','imported','merged','skipped')),
  place_id       text references places(id) on delete set null,
  decided_by     integer references users(id) on delete set null,
  decided_at     timestamptz,
  unique (file_id, row_no)
);
create index import_rows_queue_idx on import_rows (file_id, status);

create table area_stats (
  province             text primary key references provinces(key) on delete cascade,
  customer_count       integer not null default 0,
  prospect_count       integer not null default 0,
  coverage             numeric(5,2),
  density              numeric(10,4),
  gap_score            numeric(5,2),
  gap_level            text check (gap_level in ('High','Medium','Low')),
  gap_count            integer,
  gap_depth            numeric(7,2),
  gap_breadth          numeric(7,2),
  top_gap_segment      text,
  gap_segs             jsonb not null default '[]',
  top_segment          text,
  segment_distribution jsonb not null default '{}',
  computed_at          timestamptz not null default now()
);

create table district_stats (
  province             text not null references provinces(key) on delete cascade,
  district             text not null,
  customer_count       integer not null default 0,
  prospect_count       integer not null default 0,
  coverage             numeric(5,2),
  gap_score            numeric(5,2),
  gap_level            text check (gap_level in ('High','Medium','Low')),
  gap_count            integer,
  gap_depth            numeric(7,2),
  gap_breadth          numeric(7,2),
  top_gap_segment      text,
  gap_segs             jsonb not null default '[]',
  top_segment          text,
  segment_distribution jsonb not null default '{}',
  computed_at          timestamptz not null default now(),
  primary key (province, district)
);

create table zones (
  zone_id    text not null,
  state      text not null check (state in ('draft','live')),
  name       text not null check (btrim(name) <> ''),
  name_en    text,
  color      text,
  province   text,
  districts  text[] not null default '{}',
  geom       geometry(Polygon,4326) not null check (ST_IsValid(geom)),
  version    integer not null default 1,
  updated_by integer references users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (zone_id, state)
);
create index zones_geom_gix on zones using gist (geom);

create table zone_history (
  version    integer primary key,
  snapshot   jsonb not null,
  action     text not null check (action in ('publish','approve','restore')),
  actor_id   integer references users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table territory_assign (
  key         text primary key,
  kind        text not null check (kind in ('zone','province')),
  user_id     integer not null references users(id) on delete cascade,
  assigned_by integer references users(id) on delete set null,
  assigned_at timestamptz not null default now()
);
create index territory_assign_user_idx on territory_assign (user_id);

create table visit_plans (
  plan_id    text primary key,
  name       text not null,
  owner_id   integer not null references users(id) on delete cascade,
  visit_date date,
  round      integer not null default 1,
  saved      boolean not null default false,
  route      jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index visit_plans_owner_idx on visit_plans (owner_id, visit_date);
create trigger visit_plans_set_updated_at before update on visit_plans
  for each row execute function set_updated_at();

create table visit_plan_items (
  item_id    bigint generated always as identity primary key,
  plan_id    text not null references visit_plans(plan_id) on delete cascade,
  place_id   text not null references places(id),
  seq        integer not null,
  result     text not null default 'pending' check (result in ('success','fail','pending')),
  note       text,
  visited_at timestamptz,
  unique (plan_id, place_id)
);
create index visit_plan_items_place_idx on visit_plan_items (place_id);

create table lead_requests (
  id            bigint generated always as identity primary key,
  place_id      text references places(id) on delete set null,
  payload       jsonb,
  note          text,
  submitted_by  integer references users(id) on delete set null,
  submitted_at  timestamptz not null default now(),
  status        text not null default 'pending' check (status in ('pending','converted','rejected')),
  reviewed_by   integer references users(id) on delete set null,
  reviewed_at   timestamptz,
  reject_reason text,
  reject_note   text,
  owner_id      integer references users(id) on delete set null,
  cust_type     text,
  check (status <> 'rejected' or reject_reason is not null),
  check (status = 'pending' or reviewed_at is not null)
);
create index lead_requests_queue_idx on lead_requests (status, submitted_at);
create index lead_requests_submitter_idx on lead_requests (submitted_by);

create table lead_request_files (
  id          bigint generated always as identity primary key,
  request_id  bigint not null references lead_requests(id) on delete cascade,
  filename    text not null,
  stored_path text not null,
  mime        text,
  size_bytes  bigint not null check (size_bytes > 0),
  uploaded_at timestamptz not null default now()
);
create index lead_request_files_request_idx on lead_request_files (request_id);

create table audit_log (
  log_id      bigint generated always as identity primary key,
  actor_id    integer,
  actor_email text not null,
  event_type  text not null check (event_type ~ '^[a-z][a-z_]*$'),
  target      text,
  detail      jsonb not null default '{}',
  ip_address  inet,
  occurred_at timestamptz not null default now()
);
create index audit_log_occurred_at_idx on audit_log (occurred_at desc);
create index audit_log_actor_idx on audit_log (actor_email, occurred_at desc);
create index audit_log_event_idx on audit_log (event_type, occurred_at desc);

create function audit_log_block_change() returns trigger language plpgsql as $$
begin
  raise exception 'audit_log is append-only';
end
$$;
create trigger audit_log_no_change before update or delete on audit_log
  for each row execute function audit_log_block_change();
create trigger audit_log_no_truncate before truncate on audit_log
  for each statement execute function audit_log_block_change();

create table notifications (
  id         bigint generated always as identity primary key,
  user_id    integer not null references users(id) on delete cascade,
  event_key  text not null,
  priority   text,
  title      text not null,
  body       text,
  link       text,
  payload    jsonb not null default '{}',
  created_at timestamptz not null default now(),
  read_at    timestamptz
);
create index notifications_inbox_idx on notifications (user_id, created_at desc) where read_at is null;

create table settings (
  key        text primary key,
  value      jsonb not null,
  updated_by integer references users(id) on delete set null,
  updated_at timestamptz not null default now()
);
