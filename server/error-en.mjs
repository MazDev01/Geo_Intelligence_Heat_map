export function errorEN(msg) {
  if (typeof msg !== 'string') return msg;
  if (Object.hasOwn(EXACT, msg)) return EXACT[msg];
  for (const [re, fn] of RULES) { const m = msg.match(re); if (m) return fn(m); }
  return msg;
}

export const wantsEN = req => /^en\b/i.test(String((req && req.headers && req.headers['x-lang']) || ''));

